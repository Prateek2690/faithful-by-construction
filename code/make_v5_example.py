L = ["% worked example: Gemini 2.5 Flash, informed prompt, slack-focused run, problem 248 (generated by make_v5_example.py)",
     f"\\newcommand{{\\exDate}}{{{d.strftime('%B')} {d.day}, {d.year}}}",
     f"\\newcommand{{\\exObj}}{{{ex['objective_pct']:.2f}}}",
     f"\\newcommand{{\\exCapTrue}}{{{ex['true_bp']['issuer_cap']:.1f}}}",
     f"\\newcommand{{\\exDurTrue}}{{{ex['true_bp']['duration_ceiling']:.2f}}}",
     f"\\newcommand{{\\exCapClaim}}{{{fmt(ex['claimed_bp']['issuer_cap'])}}}",
     f"\\newcommand{{\\exDurClaim}}{{{fmt(ex['claimed_bp']['duration_ceiling'])}}}",
     f"\\newcommand{{\\exQualClaim}}{{{fmt(ex['claimed_bp']['quality_floor'])}}}",
     f"\\newcommand{{\\exAvgQ}}{{{ex['avg_q']:.3f}}}",
     f"\\newcommand{{\\exQFloor}}{{{ex['q_floor']:.3f}}}",
     f"\\newcommand{{\\exAtCap}}{{{ex['at_cap']}}}"]
open("numbers_v5_example.tex", "w").write("\n".join(L) + "\n")
print("\n".join(L))
