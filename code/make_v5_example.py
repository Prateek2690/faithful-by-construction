"""Writes numbers_v5_example.tex: macros for the worked example in Section 5.1
(Gemini 2.5 Flash, with-facts prompt, slack-focused set, problem 248). Run after make_v5_numbers.py."""
import json, datetime
S = json.load(open("v5_summary.json"))
ex = [e for e in S["examples"] if e["i"] == 248 and e["model"] == "google/gemini-2.5-flash"][0]
d = datetime.date.fromisoformat(ex["date"])
