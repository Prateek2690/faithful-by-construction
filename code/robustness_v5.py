"""Extra checks on the saved v5 results (no API calls).
Writes robustness_v5.json and numbers_v5_robust.tex."""
import json, math, collections
from math import comb
C = ["issuer_cap", "duration_ceiling", "quality_floor"]
RUNS = {"main": "final_results.json", "slack": "final_results_slack.json"}
MODELS = {"Son": "anthropic/claude-sonnet-4.5", "Gem": "google/gemini-2.5-flash", "Gpt": "openai/gpt-4o-mini"}

def mcnemar_exact(b, c):
    n = b + c
    if n == 0: return 1.0
    k = min(b, c)
    p = 2 * sum(comb(n, i) for i in range(k + 1)) / 2 ** n
    return min(1.0, p)

R = {run: json.load(open(f))["per_problem"] for run, f in RUNS.items()}
out = {"explainers": {}, "paired": {}, "by_limit": {}, "tolerance": {}}
cases = collections.defaultdict(dict)   # explainer -> {(run,i,c): named?} for zero-effect cases
for name in R["main"]:
    zn = zk = bn = bk = all3 = nexp = nnamed = 0
    bl = collections.defaultdict(lambda: [0, 0])
    for run, P in R.items():
        for r in P[name]:
            eff, nm = set(r["effective"]), set(r["named"])
            nexp += 1; nnamed += len(nm); all3 += (len(nm) == 3)
            for c in C:
                if c in eff:
                    bn += 1; bk += (c in nm)
                else:
                    zn += 1; zk += (c in nm); bl[c][1] += 1; bl[c][0] += (c in nm)
                    cases[name][(run, r["i"], c)] = (c in nm)
    out["explainers"][name] = {"zero_named": [zk, zn], "binding_named": [bk, bn],
                               "p_named_given_zero": zk / zn, "p_named_given_binding": bk / bn,
                               "share_name_all3": all3 / nexp, "mean_named": nnamed / nexp, "n_expl": nexp}
    out["by_limit"][name] = {c: v for c, v in bl.items()}

def paired(a, b):
    A, B = cases[a], cases[b]; keys = set(A) & set(B)
    b_ = sum(1 for k in keys if A[k] and not B[k]); c_ = sum(1 for k in keys if B[k] and not A[k])
    return {"n": len(keys), "a_only": b_, "b_only": c_, "p": mcnemar_exact(b_, c_)}

for s, m in MODELS.items():
    out["paired"][f"{s}_basic_vs_facts"] = paired(f"{m}/FF", f"{m}/FF_informed")
out["paired"]["Son_vs_Gem_basic"] = paired(f"{MODELS['Son']}/FF", f"{MODELS['Gem']}/FF")
out["paired"]["Son_vs_Gem_facts"] = paired(f"{MODELS['Son']}/FF_informed", f"{MODELS['Gem']}/FF_informed")
out["paired"]["Gem_facts_vs_template"] = paired(f"{MODELS['Gem']}/FF_informed", "ALWAYS_CAP_DUR")
out["paired"]["Son_facts_vs_template"] = paired(f"{MODELS['Son']}/FF_informed", "ALWAYS_CAP_DUR")

S = json.load(open("v5_summary.json"))
for key, rs in S["ratios"].items():
    rs = [x for x in rs if x is not None]   # a claim of 0 bp for a binding limit counts (ratio 0)
    out["tolerance"][key] = {"n": len(rs), **{f"tol{t}": sum(abs(x - 1) <= t for x in rs) / len(rs) for t in (0.2, 0.35, 0.5)},
                             "within2x": sum(0.5 <= x <= 2 for x in rs) / len(rs)}
pool = [x for k, v in S["ratios"].items() if not k.startswith("openai") for x in v if x is not None]
out["tolerance"]["pooled_son_gem"] = {"n": len(pool), **{f"tol{t}": sum(abs(x - 1) <= t for x in pool) / len(pool) for t in (0.2, 0.35, 0.5)},
                                      "within2x": sum(0.5 <= x <= 2 for x in pool) / len(pool)}
json.dump(out, open("robustness_v5.json", "w"), indent=1)

L = ["% generated by robustness_v5.py"]
def mac(n, v): L.append(f"\\newcommand{{\\{n}}}{{{v}}}")
pc = lambda x: f"{100*x:.0f}"
def pfmt(p):
    if p >= 0.001: return f"{p:.2g}"
    m, e = f"{p:.1e}".split("e"); return f"{m}\\times10^{{{int(e)}}}"
for s, m in MODELS.items():
    for cond, tag in [("FF", "Ff"), ("FF_informed", "Inf")]:
        e = out["explainers"][f"{m}/{cond}"]
        mac(f"bind{s}{tag}", pc(e["p_named_given_binding"])); mac(f"allthree{s}{tag}", pc(e["share_name_all3"]))
    p = out["paired"][f"{s}_basic_vs_facts"]; mac(f"mcn{s}", pfmt(p['p'])); mac(f"mcn{s}Ab", p["a_only"]); mac(f"mcn{s}Ba", p["b_only"])
e = out["explainers"]["CG"]; mac("bindCG", pc(e["p_named_given_binding"]))
e = out["explainers"]["ALWAYS_CAP_DUR"]; mac("bindTmpl", pc(e["p_named_given_binding"]))
mac("mcnSonGem", pfmt(out['paired']['Son_vs_Gem_basic']['p']))
mac("mcnGemTmpl", pfmt(out['paired']['Gem_facts_vs_template']['p']))
t = out["tolerance"]["pooled_son_gem"]
import statistics
for c, ct in [("issuer_cap", "Cap"), ("duration_ceiling", "Dur"), ("quality_floor", "Qual")]:
    vals = [x for k, v in S["ratios"].items() if not k.startswith("openai") and k.endswith(c) for x in v if x is not None]
    mac(f"ratioMain{ct}", f"{statistics.median(vals):.2f}")   # Claude + Gemini, both prompts, both problem sets
mk = [k for k in S["magnitude"] if not k.startswith("openai")]
nmag = sum(S["magnitude"][k]["n_claims"] for k in mk)
mac("nMagMain", f"{nmag:,}")
mac("magMain", pc(sum(S["magnitude"][k]["within35"] * S["magnitude"][k]["n_claims"] for k in mk) / nmag))
mac("tolTwenty", pc(t["tol0.2"])); mac("tolThirtyFive", pc(t["tol0.35"])); mac("tolFifty", pc(t["tol0.5"])); mac("tolTwoX", pc(t["within2x"])); mac("tolN", t["n"])
open("numbers_v5_robust.tex", "w").write("\n".join(L) + "\n")
print(json.dumps({k: {kk: (round(vv, 3) if isinstance(vv, float) else vv) for kk, vv in v.items()} for k, v in out["explainers"].items()}, indent=0))
print(json.dumps(out["paired"], indent=0)); print(json.dumps(out["by_limit"], indent=0)); print(json.dumps(out["tolerance"]["pooled_son_gem"]))

# cluster bootstrap (resample problems, keep all zero-effect limits of a problem together)
import random
random.seed(0)
boot = {}
for name in [f"{MODELS['Son']}/FF", f"{MODELS['Son']}/FF_informed", f"{MODELS['Gem']}/FF", f"{MODELS['Gem']}/FF_informed"]:
    clusters = collections.defaultdict(list)
    for (run, i, c), v in cases[name].items():
        clusters[(run, i)].append(v)
    keys = list(clusters); rates = []
    for _ in range(4000):
        smp = [clusters[random.choice(keys)] for _ in keys]
        k = sum(sum(s) for s in smp); n = sum(len(s) for s in smp); rates.append(k / n)
    rates.sort(); boot[name] = [rates[int(0.025 * len(rates))], rates[int(0.975 * len(rates))]]
out["cluster_boot_ci"] = boot
json.dump(out, open("robustness_v5.json", "w"), indent=1)
with open("numbers_v5_robust.tex", "a") as f:
    for s, tag, nm in [("Son", "Ff", "FF"), ("Son", "Inf", "FF_informed"), ("Gem", "Ff", "FF"), ("Gem", "Inf", "FF_informed")]:
        lo, hi = boot[f"{MODELS[s]}/{nm}"]
        f.write(f"\\newcommand{{\\cb{s}{tag}}}{{{100*lo:.0f}--{100*hi:.0f}}}\n")
print("cluster bootstrap", boot)
